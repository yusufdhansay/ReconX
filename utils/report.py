"""Report generation: structured JSON and a styled HTML report."""

import html
import json
import os
from datetime import datetime

from utils import logger


def _timestamp():
    return datetime.now().strftime("%Y%m%d_%H%M%S")


def _safe(value):
    """HTML-escape a value for safe insertion into the report."""
    if value is None:
        return "<em>n/a</em>"
    if isinstance(value, list):
        if not value:
            return "<em>none</em>"
        return "<br>".join(html.escape(str(v)) for v in value)
    return html.escape(str(value))


def write_json(results, output_dir, domain):
    """Write the full results dict to a timestamped JSON file."""
    path = os.path.join(output_dir, f"report_{domain}_{_timestamp()}.json")
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(results, handle, indent=2, default=str)
    return path


def _rows_subdomains(subdomains):
    if not subdomains:
        return "<tr><td colspan='1'><em>None found</em></td></tr>"
    return "".join(f"<tr><td>{_safe(s)}</td></tr>" for s in subdomains)


def _rows_ports(ports):
    if not ports:
        return "<tr><td colspan='2'><em>No open ports</em></td></tr>"
    return "".join(
        f"<tr><td>{_safe(p['port'])}</td><td>{_safe(p['service'])}</td></tr>"
        for p in ports
    )


def _rows_whois(whois_data):
    fields = [
        ("Registrar", whois_data.get("registrar")),
        ("Creation Date", whois_data.get("creation_date")),
        ("Expiration Date", whois_data.get("expiration_date")),
        ("Name Servers", whois_data.get("name_servers")),
    ]
    return "".join(
        f"<tr><td class='key'>{html.escape(k)}</td><td>{_safe(v)}</td></tr>"
        for k, v in fields
    )


def _rows_tech(tech):
    fields = [
        ("URL", tech.get("url")),
        ("Server", tech.get("server")),
        ("X-Powered-By", tech.get("powered_by")),
        ("CMS", tech.get("cms")),
        ("CDN", tech.get("cdn")),
    ]
    return "".join(
        f"<tr><td class='key'>{html.escape(k)}</td><td>{_safe(v)}</td></tr>"
        for k, v in fields
    )


def _rows_emails(emails):
    if not emails:
        return "<tr><td><em>None found</em></td></tr>"
    return "".join(f"<tr><td>{_safe(e)}</td></tr>" for e in emails)


