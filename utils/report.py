def write_html(results, output_dir, domain):
    """Render a clean HTML report and write it to a timestamped file."""
    subdomains = results.get("subdomains", [])
    ports = results.get("ports", [])
    whois_data = results.get("whois", {})
    tech = results.get("tech", {})
    emails = results.get("emails", [])

    content = HTML_TEMPLATE.format(
        domain=html.escape(domain),
        generated=datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        sub_count=len(subdomains),
        sub_rows=_rows_subdomains(subdomains),
        port_count=len(ports),
        port_rows=_rows_ports(ports),
        whois_rows=_rows_whois(whois_data),
        tech_rows=_rows_tech(tech),
        email_count=len(emails),
        email_rows=_rows_emails(emails),
    )

    path = os.path.join(output_dir, f"report_{domain}_{_timestamp()}.html")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(content)
    return path


def generate(results, output_dir, domain):
    """Generate both JSON and HTML reports. Returns their paths."""
    logger.info("Generating reports...")
    json_path = write_json(results, output_dir, domain)
    html_path = write_html(results, output_dir, domain)
    logger.success(f"JSON report: {json_path}")
    logger.success(f"HTML report: {html_path}")
    return json_path, html_path
